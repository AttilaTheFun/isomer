import Foundation
import SwiftFFIIRLibrary

// The C-header backend: declares the `swift_ffi_<module>_*` symbols — the
// shared C ABI every per-language layer (C++, the JNI adapter) calls through.
// Not intended for direct application consumption (docs/bridge_v2.md).
//
// Conventions: scalars flat; strings/bytes (ptr, len) in and +1 box out;
// everything erased (structs, Result values, generic arguments) as blobs in
// the swift_abi.h wire encoding, (ptr, len) in and +1 box out; closures as
// `bridge_closure` dispatchers; interfaces as dual-slot (+1 boxes out);
// `Lazy` returns as deferred handles; async functions with a trailing
// completion dispatcher.
extension Generator {
    // MARK: - C header

    func cType(_ swift: String, interfaces: Set<String>) -> String {
        switch swift {
        case "Int": return "intptr_t"
        case "Int32": return "int32_t"
        case "Double": return "double"
        case "Bool": return "bool"
        case "Void", "()": return "void"
        case "String", "[UInt8]": return "void *"
        default: return interfaces.contains(swift) ? "void *" : "intptr_t"
        }
    }

    /// The C parameter list for a bridged signature (concrete or generic).
    func cParamList(
        _ parameters: [FFIParameter], leading: [String], generics: Set<String>,
        interfaces: Set<String>
    ) -> [String] {
        var params = leading
        for (index, parameter) in parameters.enumerated() {
            if parameter.closure != nil {
                params.append("const bridge_closure *p\(index)")
            } else if isBuffer(parameter.type) || isBlob(parameter.type, generics: generics) {
                params.append("const void *p\(index)")
                params.append("int32_t p\(index)_len")
            } else if interfaces.contains(parameter.type) {
                // Dual slot: exactly one of (Swift handle, foreign dispatcher).
                params.append("void *p\(index)")
                params.append("const bridge_closure *p\(index)_foreign")
            } else {
                params.append("\(cType(parameter.type, interfaces: interfaces)) p\(index)")
            }
        }
        return params
    }

    /// The C return type for a bridged signature.
    func cReturnType(
        _ function: FFIFunction, generics: Set<String>, interfaces: Set<String>
    ) -> String {
        if function.returnsLazy { return "void *" }
        if isBlob(function.returnType, generics: generics) { return "void *" }
        return cType(function.returnType, interfaces: interfaces)
    }

    func emitCHeader(_ module: FFIModule, moduleName: String) -> String {
        let interfaces = module.interfaceNames
        let guardName = moduleName.uppercased()

        var out = """
            // Generated by swift_ffi. Do not edit.
            //
            // The C ABI of the `\(moduleName)` bridge, exactly as the SwiftFFI macros
            // expand it into the annotated module (`@c(swift_ffi_[<ns>_]<name>)`).
            // This layer is an implementation detail: consume it through the
            // generated per-language bindings (Kotlin / C++ / TypeScript), not
            // directly. The fixed-name runtime entry points (swift_ffi_alloc,
            // the byte-box drains, Lazy handles) are declared by swift_abi.h.
            #ifndef SWIFT_FFI_\(guardName)_H
            #define SWIFT_FFI_\(guardName)_H

            #include <stdbool.h>
            #include <stdint.h>

            #include "swift_abi.h"

            #ifdef __cplusplus
            extern "C" {
            #endif

            """

        for interface in module.interfaces {
            out += """

                // \(interface.name): +1 handles; release exactly once. Method calls are
                // ordinal-led blob dispatches: `args` is a borrowed concatenation of the
                // method's argument blobs; the return is a +1 box of the result blob (a
                // VOID blob for void, an ERROR blob on failure).
                void *\(invokeSymbol(interface))(void *handle, int32_t ordinal, const void *args, int32_t args_len);
                void \(releaseSymbol(interface))(void *handle);

                """
        }

        out += "\n"
        for function in module.functions {
            let generics = Set(function.genericParameters)
            var params = cParamList(
                function.parameters, leading: [], generics: generics, interfaces: interfaces)
            if function.isAsync {
                // Completion dispatcher: invoked with the result blob (VOID /
                // value / HANDLE) or an ERROR blob.
                params.append("const bridge_closure *completion")
                out += "void \(symbol(function))(\(params.joined(separator: ", ")));\n"
                continue
            }
            if function.isThrowing {
                // On failure the return is zero/NULL and *error_out is a +1 string
                // box with the message; on success *error_out is untouched.
                params.append("void **error_out")
            }
            let ret = cReturnType(function, generics: generics, interfaces: interfaces)
            let paramList = params.isEmpty ? "void" : params.joined(separator: ", ")
            out += "\(ret) \(symbol(function))(\(paramList));\n"
        }

        out += """

            #ifdef __cplusplus
            }
            #endif

            #endif

            """
        return out
    }
}
