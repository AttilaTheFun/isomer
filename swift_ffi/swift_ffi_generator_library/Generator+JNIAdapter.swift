import Foundation
import SwiftFFIIRLibrary

// The JNI-adapter backend: a small generated C file mapping `Java_*` JNI
// symbols onto the module's shared C ABI, so Kotlin consumes Swift through
// the same generated C layer as every other language (docs/bridge_v2.md).
// The adapter interprets nothing: byte arrays pass through as (ptr, len),
// boxes are drained to byte arrays, and callback objects (closures, foreign
// interface dispatchers, async completions) wrap a single Kotlin
// `swiftffi.SwiftClosure` in a `bridge_closure` vtable.
extension Generator {
    // The Kotlin external names (shared with the Kotlin backend). The `Raw`
    // suffix is camelCase-appended WITHOUT an underscore: an underscore would
    // JNI-mangle to `_1` and break the symbol match.
    func jniFunctionName(_ name: String) -> String { "\(name)Raw" }
    func jniReleaseName(_ interface: String) -> String { "\(lowerFirst(interface))ReleaseRaw" }
    func jniInvokeName(_ interface: String) -> String { "\(lowerFirst(interface))InvokeRaw" }
    func jniLazyGetName() -> String { "lazyGetRaw" }
    func jniLazyReleaseName() -> String { "lazyReleaseRaw" }

    /// Escapes one identifier segment for a JNI symbol (`_` → `_1`).
    func jniEscape(_ segment: String) -> String {
        segment.replacingOccurrences(of: "_", with: "_1")
    }

    /// The `Java_<pkg>_<Class>Native_<fn>` symbol for a Kotlin external.
    func jniSymbol(package: String, className: String, function: String) -> String {
        let pkg = package.split(separator: ".").map { jniEscape(String($0)) }.joined(separator: "_")
        return "Java_\(pkg)_\(jniEscape(className))Native_\(jniEscape(function))"
    }

    func emitJNIAdapter(
        _ module: FFIModule, moduleName: String, package: String, className: String,
        headerName: String
    ) -> String {
        let interfaces = module.interfaceNames

        var out = """
            // Generated by swift_ffi. Do not edit.
            //
            // JNI adapter: maps the Kotlin externals of `\(className)Native` onto the
            // module's `swift_ffi_*` C ABI. Pure marshaling — no bridge semantics live here.
            #include <jni.h>
            #include <stdlib.h>
            #include <string.h>

            #include "swift_abi.h"
            #include "\(headerName)"

            // --- Kotlin callback objects as bridge_closure dispatchers ---------------

            typedef struct swift_ffi_jni_ctx {
                JavaVM *vm;
                jobject global;   /* a swiftffi.SwiftClosure */
                int refs;   /* mutated only via __atomic_* builtins */
            } swift_ffi_jni_ctx;

            static JNIEnv *swift_ffi_jni_env(swift_ffi_jni_ctx *ctx, int *attached) {
                JNIEnv *env = NULL;
                *attached = 0;
                if ((*ctx->vm)->GetEnv(ctx->vm, (void **)&env, JNI_VERSION_1_6) != JNI_OK) {
                    if ((*ctx->vm)->AttachCurrentThread(ctx->vm, &env, NULL) != JNI_OK) return NULL;
                    *attached = 1;
                }
                return env;
            }

            static void swift_ffi_jni_invoke(void *raw, const void *args, int64_t args_len,
                                             bridge_buf *result_out, bridge_buf *error_out) {
                swift_ffi_jni_ctx *ctx = (swift_ffi_jni_ctx *)raw;
                int attached = 0;
                JNIEnv *env = swift_ffi_jni_env(ctx, &attached);
                if (!env) return;
                jbyteArray jargs = (*env)->NewByteArray(env, (jsize)args_len);
                if (args_len > 0) {
                    (*env)->SetByteArrayRegion(env, jargs, 0, (jsize)args_len, (const jbyte *)args);
                }
                jclass cls = (*env)->GetObjectClass(env, ctx->global);
                jmethodID mid = (*env)->GetMethodID(env, cls, "invoke", "([B)[B");
                jbyteArray jres = (jbyteArray)(*env)->CallObjectMethod(env, ctx->global, mid, jargs);
                if ((*env)->ExceptionCheck(env)) {
                    (*env)->ExceptionClear(env);
                    /* An ERROR blob: i32 tag, i32 aux, i64 len, message bytes. */
                    static const char message[] = "Kotlin callback threw";
                    int64_t message_len = (int64_t)sizeof(message) - 1;
                    int64_t blob_len = 4 + 4 + 8 + message_len;
                    unsigned char *blob = (unsigned char *)bridge_alloc(blob_len);
                    int32_t tag = 10, aux = 0;
                    memcpy(blob, &tag, 4);
                    memcpy(blob + 4, &aux, 4);
                    memcpy(blob + 8, &message_len, 8);
                    memcpy(blob + 16, message, (size_t)message_len);
                    error_out->ptr = blob;
                    error_out->len = blob_len;
                } else if (jres) {
                    jsize len = (*env)->GetArrayLength(env, jres);
                    void *copy = bridge_alloc(len);
                    if (len > 0) {
                        (*env)->GetByteArrayRegion(env, jres, 0, len, (jbyte *)copy);
                    }
                    result_out->ptr = copy;
                    result_out->len = len;
                    (*env)->DeleteLocalRef(env, jres);
                }
                (*env)->DeleteLocalRef(env, jargs);
                (*env)->DeleteLocalRef(env, cls);
                if (attached) (*ctx->vm)->DetachCurrentThread(ctx->vm);
            }

            static void swift_ffi_jni_retain(void *raw) {
                swift_ffi_jni_ctx *ctx = (swift_ffi_jni_ctx *)raw;
                __atomic_add_fetch(&ctx->refs, 1, __ATOMIC_SEQ_CST);
            }

            static void swift_ffi_jni_release(void *raw) {
                swift_ffi_jni_ctx *ctx = (swift_ffi_jni_ctx *)raw;
                if (__atomic_sub_fetch(&ctx->refs, 1, __ATOMIC_SEQ_CST) <= 0) {
                    int attached = 0;
                    JNIEnv *env = swift_ffi_jni_env(ctx, &attached);
                    if (env) {
                        (*env)->DeleteGlobalRef(env, ctx->global);
                        if (attached) (*ctx->vm)->DetachCurrentThread(ctx->vm);
                    }
                    free(ctx);
                }
            }

            /* Wraps a Kotlin SwiftClosure in a caller-owned bridge_closure (creation
             * reference included; the caller releases after the bridged call). */
            static bridge_closure swift_ffi_jni_wrap(JNIEnv *env, jobject callback) {
                swift_ffi_jni_ctx *ctx = (swift_ffi_jni_ctx *)malloc(sizeof *ctx);
                (*env)->GetJavaVM(env, &ctx->vm);
                ctx->global = (*env)->NewGlobalRef(env, callback);
                ctx->refs = 1;
                bridge_closure closure = {ctx, swift_ffi_jni_invoke, swift_ffi_jni_retain,
                                          swift_ffi_jni_release};
                return closure;
            }

            /* Drains a +1 byte box into a Java byte[] and releases it. */
            static jbyteArray swift_ffi_jni_take_box(JNIEnv *env, void *box) {
                if (!box) return NULL;
                int32_t len = swift_ffi_string_len(box);
                jbyteArray array = (*env)->NewByteArray(env, len);
                if (len > 0) {
                    void *tmp = malloc((size_t)len);
                    swift_ffi_string_copy(box, tmp);
                    (*env)->SetByteArrayRegion(env, array, 0, len, (const jbyte *)tmp);
                    free(tmp);
                }
                swift_ffi_string_release(box);
                return array;
            }

            /* Throws swiftffi.SwiftError with the message in a +1 string box. */
            static void swift_ffi_jni_throw(JNIEnv *env, void *box) {
                int32_t len = swift_ffi_string_len(box);
                char *message = (char *)malloc((size_t)len + 1);
                swift_ffi_string_copy(box, message);
                message[len] = 0;
                swift_ffi_string_release(box);
                jclass cls = (*env)->FindClass(env, "swiftffi/SwiftError");
                if (cls) (*env)->ThrowNew(env, cls, message);
                free(message);
            }

            """

        // --- Function/method emission helpers -------------------------------

        /// One JNI export mapping to one C-ABI call.
        func emitEntry(
            symbolFunction: String,
            parameters: [FFIParameter],
            returnType: String,
            returnsLazy: Bool,
            generics: Set<String>,
            isThrowing: Bool,
            isAsync: Bool,
            handle: Bool,
            cSymbol: String
        ) -> String {
            var jniParams: [String] = ["JNIEnv *env", "jclass clazz"]
            if handle { jniParams.append("jlong handle") }
            var prelude: [String] = []
            var args: [String] = handle ? ["(void *)(intptr_t)handle"] : []
            var cleanup: [String] = []

            for (index, parameter) in parameters.enumerated() {
                let p = "p\(index)"
                if parameter.closure != nil {
                    jniParams.append("jobject \(p)")
                    prelude.append("bridge_closure closure\(index) = swift_ffi_jni_wrap(env, \(p));")
                    args.append("&closure\(index)")
                    cleanup.append("swift_ffi_jni_release(closure\(index).ctx);")
                } else if isBuffer(parameter.type) || isBlob(parameter.type, generics: generics) {
                    jniParams.append("jbyteArray \(p)")
                    prelude.append("jsize \(p)_len = \(p) ? (*env)->GetArrayLength(env, \(p)) : 0;")
                    prelude.append("jbyte *\(p)_bytes = \(p) ? (*env)->GetByteArrayElements(env, \(p), NULL) : NULL;")
                    args.append("\(p)_bytes")
                    args.append("(int32_t)\(p)_len")
                    cleanup.append("if (\(p)) (*env)->ReleaseByteArrayElements(env, \(p), \(p)_bytes, JNI_ABORT);")
                } else if interfaces.contains(parameter.type) {
                    jniParams.append("jlong \(p)")
                    jniParams.append("jobject \(p)f")
                    prelude.append("bridge_closure foreign\(index);")
                    prelude.append("const bridge_closure *foreign\(index)_ptr = NULL;")
                    prelude.append("if (\(p)f) { foreign\(index) = swift_ffi_jni_wrap(env, \(p)f); foreign\(index)_ptr = &foreign\(index); }")
                    args.append("(void *)(intptr_t)\(p)")
                    args.append("foreign\(index)_ptr")
                    cleanup.append("if (foreign\(index)_ptr) swift_ffi_jni_release(foreign\(index).ctx);")
                } else {
                    switch parameter.type {
                    case "Int":
                        jniParams.append("jlong \(p)")
                        args.append("(intptr_t)\(p)")
                    case "Int32":
                        jniParams.append("jint \(p)")
                        args.append("\(p)")
                    case "Double":
                        jniParams.append("jdouble \(p)")
                        args.append("\(p)")
                    case "Bool":
                        jniParams.append("jboolean \(p)")
                        args.append("(\(p) != JNI_FALSE)")
                    default:
                        jniParams.append("jlong \(p)")
                        args.append("(intptr_t)\(p)")
                    }
                }
            }

            if isAsync {
                jniParams.append("jobject completion")
                prelude.append("bridge_closure completion_closure = swift_ffi_jni_wrap(env, completion);")
                args.append("&completion_closure")
                cleanup.append("swift_ffi_jni_release(completion_closure.ctx);")
            }
            if isThrowing {
                prelude.append("void *error_box = NULL;")
                args.append("&error_box")
            }

            // Return handling.
            let jniReturn: String
            let callStatement: String
            var returnStatement = ""
            let call = "\(cSymbol)(\(args.joined(separator: ", ")))"
            let erasedReturn = returnsLazy
                ? false : (isBlob(returnType, generics: generics))
            if isAsync || isVoid(returnType) && !returnsLazy {
                jniReturn = "void"
                callStatement = "\(call);"
            } else if returnsLazy || interfaces.contains(returnType) {
                jniReturn = "jlong"
                callStatement = "void *result = \(call);"
                returnStatement = "return (jlong)(intptr_t)result;"
            } else if erasedReturn || isBuffer(returnType) {
                jniReturn = "jbyteArray"
                callStatement = "void *result = \(call);"
                returnStatement = "return swift_ffi_jni_take_box(env, result);"
            } else {
                switch returnType {
                case "Int":
                    jniReturn = "jlong"
                    callStatement = "intptr_t result = \(call);"
                    returnStatement = "return (jlong)result;"
                case "Int32":
                    jniReturn = "jint"
                    callStatement = "int32_t result = \(call);"
                    returnStatement = "return result;"
                case "Double":
                    jniReturn = "jdouble"
                    callStatement = "double result = \(call);"
                    returnStatement = "return result;"
                case "Bool":
                    jniReturn = "jboolean"
                    callStatement = "bool result = \(call);"
                    returnStatement = "return result ? JNI_TRUE : JNI_FALSE;"
                default:
                    jniReturn = "jlong"
                    callStatement = "intptr_t result = \(call);"
                    returnStatement = "return (jlong)result;"
                }
            }

            var body = prelude
            body.append(callStatement)
            body.append(contentsOf: cleanup)
            if isThrowing {
                let zero: String
                switch jniReturn {
                case "void": zero = "return;"
                case "jboolean": zero = "return JNI_FALSE;"
                case "jbyteArray": zero = "return NULL;"
                case "jdouble": zero = "return 0;"
                default: zero = "return 0;"
                }
                body.append("if (error_box) { swift_ffi_jni_throw(env, error_box); \(zero) }")
            }
            if !returnStatement.isEmpty {
                body.append(returnStatement)
            }

            let symbol = jniSymbol(package: package, className: className, function: symbolFunction)
            return """

                JNIEXPORT \(jniReturn) JNICALL \(symbol)(\(jniParams.joined(separator: ", "))) {
                    (void)clazz;
                \(body.map { "    \($0)\n" }.joined())}

                """
        }

        for function in module.functions {
            out += emitEntry(
                symbolFunction: jniFunctionName(function.name),
                parameters: function.parameters,
                returnType: function.isAsync ? "Void" : function.returnType,
                returnsLazy: function.returnsLazy && !function.isAsync,
                generics: Set(function.genericParameters),
                isThrowing: function.isThrowing && !function.isAsync,
                isAsync: function.isAsync,
                handle: false,
                cSymbol: symbol(function)
            )
        }
        for interface in module.interfaces {
            out += """

                JNIEXPORT void JNICALL \(jniSymbol(package: package, className: className, function: jniReleaseName(interface.name)))(JNIEnv *env, jclass clazz, jlong handle) {
                    (void)env;
                    (void)clazz;
                    \(releaseSymbol(interface))((void *)(intptr_t)handle);
                }

                JNIEXPORT jbyteArray JNICALL \(jniSymbol(package: package, className: className, function: jniInvokeName(interface.name)))(JNIEnv *env, jclass clazz, jlong handle, jint ordinal, jbyteArray args) {
                    (void)clazz;
                    jsize args_len = args ? (*env)->GetArrayLength(env, args) : 0;
                    jbyte *args_bytes = args ? (*env)->GetByteArrayElements(env, args, NULL) : NULL;
                    void *box = \(invokeSymbol(interface))((void *)(intptr_t)handle, ordinal, args_bytes, (int32_t)args_len);
                    if (args) (*env)->ReleaseByteArrayElements(env, args, args_bytes, JNI_ABORT);
                    return swift_ffi_jni_take_box(env, box);
                }

                """
        }

        if module.interfaces.contains(where: { $0.methods.contains(where: \.isAsync) }) {
            // The host's answer to an in-flight async interface call: the fixed
            // SwiftFFI runtime entry, reached through this module's adapter.
            out += """

                extern void swift_ffi_async_resume(int32_t call_id, const void *blob, int32_t len);
                JNIEXPORT void JNICALL \(jniSymbol(package: package, className: className, function: "asyncResumeRaw"))(JNIEnv *env, jclass clazz, jint call_id, jbyteArray blob) {
                    (void)clazz;
                    jsize len = blob ? (*env)->GetArrayLength(env, blob) : 0;
                    jbyte *bytes = blob ? (*env)->GetByteArrayElements(env, blob, NULL) : NULL;
                    swift_ffi_async_resume((int32_t)call_id, bytes, (int32_t)len);
                    if (bytes) (*env)->ReleaseByteArrayElements(env, blob, bytes, JNI_ABORT);
                }

                """
        }

        if module.functions.contains(where: \.returnsLazy) {
            out += """

                JNIEXPORT jbyteArray JNICALL \(jniSymbol(package: package, className: className, function: jniLazyGetName()))(JNIEnv *env, jclass clazz, jlong handle) {
                    (void)clazz;
                    return swift_ffi_jni_take_box(env, swift_ffi_lazy_get((void *)(intptr_t)handle));
                }

                JNIEXPORT void JNICALL \(jniSymbol(package: package, className: className, function: jniLazyReleaseName()))(JNIEnv *env, jclass clazz, jlong handle) {
                    (void)env;
                    (void)clazz;
                    swift_ffi_lazy_release((void *)(intptr_t)handle);
                }

                """
        }

        return out
    }
}
