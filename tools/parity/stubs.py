#!/usr/bin/env python3
"""Writes shared/swift_ui_core/NotYet.swift: Apple's SwiftUI declarations
Isomer means to have (a "planned" group in tools/parity/reasons/SwiftUI.json)
and doesn't yet, as `@available(*, unavailable, message:)` stubs, so the
compiler names the gap ("Not yet in Isomer: …") where it would otherwise
say there is no such member. docs/isomer_031_plan.md's rule: planned API
whose types all exist is declared unavailable; the rest stays absent.

    tools/parity/stubs.py            (after tools/parity/parity.py, which
                                      leaves the symbol graphs in /tmp)

A declaration is stubbed when it is a method, property or initializer of a
type Isomer's SwiftUI declares; every type it names exists in Isomer (or is
the standard library's); and Isomer has nothing of that base name on that
type (a stub beside an implemented overload could make a call that works
now ambiguous). Each stub is then compiled: one the compiler rejects is
left out and the file written again, until it builds (--no-build skips
that).
"""

import collections
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import parity as P  # noqa: E402

OUT = os.path.join(P.ROOT, "shared", "swift_ui_core", "NotYet.swift")
SKIP_FILE = os.path.join(P.ROOT, "tools", "parity", "stubs_skip.txt")
HEADER = """// Generated by tools/parity/stubs.py: do not edit.
//
// Apple's SwiftUI declarations Isomer means to have and doesn't yet, as
// unavailable stubs: the compiler says "Not yet in Isomer" and why, where it
// would otherwise say there is no such member. docs/parity/SwiftUI.md lists
// them with everything else that is missing.

import CoreGraphics
import Foundation

"""

# Members that satisfy the protocols a type conforms to.
WITNESS_NAMES = {
    "hash(into:)", "hashValue", "encode(to:)", "init(from:)", "description", "debugDescription", "id", "body",
    "makeBody(configuration:)", "path(in:)", "rawValue", "init(rawValue:)", "allCases", "==(_:_:)", "<(_:_:)",
    "animatableData", "customMirror", "sizeThatFits(_:)", "sizeThatFits(_:subviews:cache:)",
    "placeSubviews(in:proposal:subviews:cache:)", "makeCache(subviews:)", "updateCache(_:subviews:)",
    "defaultValue", "reduce(value:nextValue:)", "resolve(in:)", "init(stringLiteral:)", "init(integerLiteral:)",
    "init(floatLiteral:)", "init(booleanLiteral:)", "init(unicodeScalarLiteral:)", "init(extendedGraphemeClusterLiteral:)",
    "init(nilLiteral:)", "init(arrayLiteral:)", "init(dictionaryLiteral:)", "init(stringInterpolation:)",
}

DROP_ATTRIBUTES = re.compile(r"^(@export\([^)]*\)|@_alwaysEmitIntoClient|@backDeployed\([^)]*\)|@preconcurrency|@_disfavoredOverload|@inlinable|@usableFromInline|@_spi\([^)]*\))\s*")
UNSUPPORTED = re.compile(r"\b(consuming|borrowing|sending|isolated|~Copyable|~Escapable|some\s+\w+\s*&|@_lifetime|@lifetime|_const|async)\b")


def type_paths(symbols):
    return {tuple(s["pathComponents"]) for s in symbols if P.KIND_GROUPS.get(s["kind"]["identifier"]) == "type"}


def main(argv):
    apple = P.load(P.APPLE_DIR, "SwiftUI") + P.load(P.APPLE_DIR, "SwiftUICore")
    isomer = P.load(P.ISOMER_DIR, "SwiftUI", own_only=True)
    others = (P.load(P.ISOMER_DIR, "Foundation") + P.load(P.ISOMER_DIR, "FoundationEssentials")
              + P.load(P.ISOMER_DIR, "CoreGraphics"))
    reasons = json.load(open(os.path.join(P.REASONS_DIR, "SwiftUI.json")))
    _, missing, _, _, _, _ = P.compare(apple, isomer)
    groups, _ = P.classify(missing, reasons)

    apple_by_precise = {s["identifier"]["precise"]: s for s in apple}
    # Requirements and their default implementations, and what witnesses a
    # conformance the compiler synthesizes: a stub there would take the
    # conformance's place.
    witnesses = set()
    for module in ("SwiftUI", "SwiftUICore"):
        for path in [os.path.join(P.APPLE_DIR, module + ".symbols.json")]:
            for relationship in json.load(open(path)).get("relationships", []):
                if relationship["kind"] in ("requirementOf", "optionalRequirementOf", "defaultImplementationOf"):
                    witnesses.add(relationship["source"])
    isomer_types = type_paths(isomer)
    other_types = type_paths(others)
    # Base names Isomer has on each type (any kind).
    taken = collections.defaultdict(set)
    for s in isomer:
        path = s["pathComponents"]
        if len(path) >= 2:
            taken[tuple(path[:-1])].add(path[-1].split("(")[0])
    isomer_protocols = {tuple(s["pathComponents"]) for s in isomer if s["kind"]["identifier"] == "swift.protocol"}
    skip = set()
    if os.path.exists(SKIP_FILE):
        skip = {line.strip() for line in open(SKIP_FILE) if line.strip() and not line.startswith("#")}

    def type_exists(fragment, generics):
        name = fragment["spelling"]
        precise = fragment.get("preciseIdentifier", "")
        if name in generics or name == "Self":
            return True
        symbol = apple_by_precise.get(precise)
        if symbol is not None:
            return tuple(symbol["pathComponents"]) in isomer_types
        if precise.startswith(("s:s", "s:S")):
            return True  # the standard library
        if precise.startswith(("s:10Foundation", "s:20FoundationEssentials", "c:@S@CG", "c:@T@CG", "c:@E@CG", "s:12CoreGraphics", "c:objc(cs)NS")):
            return any(path[-1] == name for path in other_types)
        return False

    stubs = []
    for group, _, members in groups:
        if group.get("status") != "not yet" or not group.get("intent", "").startswith("planned"):
            continue
        for symbol in members:
            kind = symbol["kind"]["identifier"]
            path = tuple(symbol["pathComponents"])
            if kind not in ("swift.method", "swift.type.method", "swift.property", "swift.type.property", "swift.init"):
                continue
            if len(path) != 2 or path[:-1] not in isomer_types:
                continue
            precise = symbol["identifier"]["precise"]
            if precise in skip or precise in witnesses:
                continue
            if path[-1] in WITNESS_NAMES or path[-1].startswith("_"):
                continue
            base = path[-1].split("(")[0]
            if base in taken[path[:-1]]:
                continue
            fragments = symbol["declarationFragments"]
            generics = {f["spelling"] for f in fragments if f["kind"] == "genericParameter"}
            extension = symbol.get("swiftExtension", {})
            constraints = extension.get("constraints", [])
            if not all(type_exists(f, generics) for f in fragments if f["kind"] == "typeIdentifier"):
                continue
            declaration = "".join(f["spelling"] for f in fragments).replace("\n", " ")
            while True:
                stripped = DROP_ATTRIBUTES.sub("", declaration)
                if stripped == declaration:
                    break
                declaration = stripped
            if UNSUPPORTED.search(declaration) or declaration.startswith("@") and not declaration.startswith(("@MainActor", "nonisolated")):
                continue
            parent = path[0]
            is_protocol = path[:-1] in isomer_protocols
            # The body: what makes the declaration compile.
            if kind in ("swift.property", "swift.type.property"):
                if "{ get set }" in declaration or "set }" in declaration:
                    continue
                declaration = re.sub(r"\s*\{\s*get\s*\}\s*$", "", declaration)
                body = "{ fatalError() }"
            elif kind == "swift.init":
                if is_protocol:
                    continue
                body = "{ fatalError() }"
            else:
                opaque = re.search(r"->\s*some\s+(\w+)", declaration)
                if opaque:
                    # `self` is the underlying type when the stub is on the
                    # protocol it returns some of (View's modifiers).
                    if not (is_protocol and opaque.group(1) == parent) and parent not in ("Text", "Image"):
                        continue
                    body = "{ self }"
                else:
                    body = "{ fatalError() }"
            where = ""
            if constraints:
                parts = []
                for c in constraints:
                    if c.get("kind") == "conformance":
                        parts.append("%s: %s" % (c["lhs"], c["rhs"]))
                    elif c.get("kind") == "sameType":
                        parts.append("%s == %s" % (c["lhs"], c["rhs"]))
                    else:
                        parts = None
                        break
                if parts is None:
                    continue
                where = " where " + ", ".join(parts)
            message = "Not yet in Isomer: %s (docs/parity/SwiftUI.md)" % group["title"]
            stubs.append({
                "precise": precise,
                "extension": "extension %s%s" % (parent, where),
                "text": '    @available(*, unavailable, message: "%s")\n    public %s %s' % (message, declaration.strip(), body),
            })

    def write(stubs):
        lines = [HEADER]
        spans = []
        for stub in stubs:
            start = len("".join(lines).splitlines()) + 1
            block = "%s {\n%s\n}\n\n" % (stub["extension"], stub["text"])
            lines.append(block)
            spans.append((start, start + block.count("\n"), stub["precise"]))
        open(OUT, "w").write("".join(lines))
        return spans

    if "--no-build" in argv:
        write(stubs)
        print("%d stubs" % len(stubs))
        return
    for attempt in range(12):
        spans = write(stubs)
        result = subprocess.run(
            ["bazel", "build", "--platforms=//tools/platforms:wasm32", "//wasm/libraries/swift_ui:swift_ui"],
            cwd=P.ROOT, capture_output=True, text=True)
        if result.returncode == 0:
            print("%d stubs, built (attempt %d)" % (len(stubs), attempt + 1))
            return
        bad = set()
        for match in re.finditer(r"NotYet\.swift:(\d+):\d+: error", result.stderr + result.stdout):
            line = int(match.group(1))
            for start, end, precise in spans:
                if start <= line <= end:
                    bad.add(precise)
        if not bad:
            print(result.stderr[-3000:])
            sys.exit("the build failed outside the stubs")
        stubs = [s for s in stubs if s["precise"] not in bad]
        print("attempt %d: %d stubs left out, %d left" % (attempt + 1, len(bad), len(stubs)))
    sys.exit("still not building after 12 attempts")


if __name__ == "__main__":
    main(sys.argv[1:])
