import Foundation

// wasm_mixed_corpus: writes a SwiftUI app whose screens are made methodically
// from Catalog.swift's pieces, modifiers, containers and screen patterns, to
// profile a runtime module with: what the runtime does for apps in general,
// not for one app (docs/side_modules.md, mixed mode's native set).
//
//   wasm_mixed_corpus [--screens N] [--items K] [--dwell-ms MS] <out.swift> [<coverage.txt>]
//
// Screen i has container c = i % C and pattern (i / C) % P, so C×P screens
// (the default, 88) cover every container with every pattern. Its K items
// g = i*K ... i*K + K-1 are pieces (m*K + j + 5c) % pieces for m = i / C:
// the screens of one container take K pieces each, consecutively, so with
// pieces/K of them every container meets every piece. A piece's n-th item
// has modifiers 2n + p and 2n + p + 1 (mod M, p the piece's index), so a
// piece used M/2 times meets every modifier. The coverage file counts each
// pair.
//
// The app shows one screen at a time (a NavigationStack each, its title
// "corpus-screen-<i>", which a driver reads), the next every --dwell-ms; each
// screen's timer changes its state ten times a second, and a driver's taps,
// drags, edits and values change the rest.

struct Options {
    var screens = 0  // C×P
    var items = 8
    var dwellMs = 2500
    var output = ""
    var coverage = ""
}

func parse() -> Options {
    var o = Options()
    var rest = Array(CommandLine.arguments.dropFirst())[...]
    var positional: [String] = []
    while let a = rest.popFirst() {
        switch a {
        case "--screens": o.screens = Int(rest.popFirst() ?? "") ?? o.screens
        case "--items": o.items = Int(rest.popFirst() ?? "") ?? o.items
        case "--dwell-ms": o.dwellMs = Int(rest.popFirst() ?? "") ?? o.dwellMs
        default: positional.append(a)
        }
    }
    guard !positional.isEmpty else {
        FileHandle.standardError.write(Data("usage: wasm_mixed_corpus [--screens N] [--items K] [--dwell-ms MS] <out.swift> [<coverage.txt>]\n".utf8))
        exit(2)
    }
    o.output = positional[0]
    if positional.count > 1 { o.coverage = positional[1] }
    return o
}

