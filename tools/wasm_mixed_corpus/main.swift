var pieceContainer: [String: Int] = [:], pieceModifier: [String: Int] = [:], containerPattern: [String: Int] = [:]
var pieceCount: [String: Int] = [:], modifierCount: [String: Int] = [:]
var occurrences: [Int: Int] = [:]

for i in 0..<o.screens {
    let container = containers[i % containers.count]
    let pattern = patterns[(i / containers.count) % patterns.count]
    containerPattern["\(container.name) × \(pattern.name)", default: 0] += 1
    var itemViews = ""
    var itemList: [String] = []
    for j in 0..<o.items {
        let p = ((i / containers.count) * o.items + j + 5 * (i % containers.count)) % pieces.count
        let piece = pieces[p]
        let n = occurrences[p, default: 0]
        occurrences[p] = n + 1
        let m1 = modifiers[(2 * n + p) % modifiers.count]
        let m2 = modifiers[(2 * n + p + 1) % modifiers.count]
        pieceCount[piece.name, default: 0] += 1
        pieceContainer["\(piece.name) × \(container.name)", default: 0] += 1
        for m in [m1, m2] {
            modifierCount[m.name, default: 0] += 1
            pieceModifier["\(piece.name) × \(m.name)", default: 0] += 1
        }
        itemViews += """
                // \(piece.name) \(m1.name) \(m2.name)
                private var item\(j): some View {
                    \(piece.code)
                        \(m1.code)
                        \(m2.code)
                }

            """
        itemList.append(container.item
            .replacingOccurrences(of: "{item}", with: "item\(j)")
            .replacingOccurrences(of: "{j}", with: "\(j)"))
    }
    let body = container.code.replacingOccurrences(
        of: "{items}", with: itemList.map { "                \($0)" }.joined(separator: "\n"))
    out += """

        // Screen \(i): \(container.name), \(pattern.name)
        struct CorpusScreen\(i): View {
        \(Catalog.state)

            var body: some View {
                \(body.replacingOccurrences(of: "\n", with: "\n            "))
                \(pattern.code)
                .navigationTitle("corpus-screen-\(i)")
                .task { await run() }
            }

        \(itemViews)
            private func run() async {
                while !Task.isCancelled {
                    try? await Task.sleep(for: .milliseconds(100))
                    tick += 1
                    if tick % 7 == 0 { withAnimation { if items.count > 6 { items.removeFirst() } else { items.append(tick) } } }
                    if tick % 13 == 0 { flag.toggle() }
                    if tick % 11 == 0 { level = Double(tick % 10) / 10 }
                    if tick % 17 == 0 { choice = (choice + 1) % 4 }
                    if tick % 19 == 0 { name = "corpus \\(tick)" }
                    if tick % 23 == 0 { withAnimation { show.toggle() } }
                    if tick % 29 == 0 { drag = CGSize(width: Double(tick % 40), height: 0) }
                    if tick % 31 == 0 { date = date.addingTimeInterval(86_400) }
                }
            }
        }

        """
}
try! out.write(toFile: o.output, atomically: true, encoding: .utf8)

if !o.coverage.isEmpty {
    func line(_ title: String, _ counts: [String: Int], of total: Int) -> String {
        "\(title): \(counts.count) of \(total) pairs (min \(counts.values.min() ?? 0), max \(counts.values.max() ?? 0))"
    }
    var report = [
        "\(o.screens) screens, \(o.screens * o.items) items",
        line("pieces", pieceCount, of: pieces.count),
        line("modifiers", modifierCount, of: modifiers.count),
        line("piece × container", pieceContainer, of: pieces.count * containers.count),
        line("piece × modifier", pieceModifier, of: pieces.count * modifiers.count),
        line("container × pattern", containerPattern, of: containers.count * patterns.count),
    ]
    report.append("")
    report += pieceCount.sorted { $0.key < $1.key }.map { "piece \($0.key): \($0.value)" }
    report += modifierCount.sorted { $0.key < $1.key }.map { "modifier \($0.key): \($0.value)" }
    try! (report.joined(separator: "\n") + "\n").write(toFile: o.coverage, atomically: true, encoding: .utf8)
    print(report.prefix(6).joined(separator: "\n"))
}
